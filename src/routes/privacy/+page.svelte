	<h1>Privacy</h1>
	<h2>The current site</h2>
	<p>The new pages don't load analytics. The theme button stores your chosen theme in your browser's local storage. The tools process the text you enter in your browser.</p>
	<p>DuckDuckGo lookup sends your search term to DuckDuckGo. The sentiment and politeness tools download models from Hugging Face and runtime files from jsDelivr when you start an analysis. Your text is processed on your device. Model files may be cached by your browser.</p>
	<p>The image and video experiments keep uploaded files in your browser. Their Save model buttons store a model in your browser's IndexedDB until you clear the site data.</p>
	<h2>Archived pages</h2>
	<p>The old Scratch project pages retain their original Google Analytics scripts and may load third-party resources. They are separate from the rebuilt pages.</p>
